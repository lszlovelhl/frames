def get_category_template(category: str | None) -> CategoryTemplate | None:
    """取品类模板；未收录返回 None（pipeline 不注入）。"""
    if not category:
        return None
    return CATEGORY_TEMPLATES.get(category)


def render_template_hint(category: str | None) -> str:
    """渲染成提示词注入文本（纯文本，供 L5 提示词追加；未收录返回空串）。"""
    tpl = get_category_template(category)
    if tpl is None:
        return ""
    lines = [f"【{category}品类模板（拆解参考，仅为倾向性引导，不得照搬句式/时间轴）】"]
    lines.append("· 常见钩子范式：" + "；".join(tpl.get("hook_patterns", [])))
    lines.append("· 结构倾向：" + "；".join(tpl.get("structure_notes", [])))
    lines.append("· 文案特征：" + "；".join(tpl.get("copywriting_style", [])))
    lines.append("· 手法倾向：" + "；".join(tpl.get("method_hints", [])))
    lines.append("· 选句策略：" + "；".join(tpl.get("quote_policy", [])))
    lines.append("· 组合模板形态：" + tpl.get("combo_shape", ""))
    hint = _HIGH_FREQ_HINTS.get(category, "")
    if hint:
        lines.append(hint)
    return "\n".join(lines)
